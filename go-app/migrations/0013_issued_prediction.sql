-- 0013_issued_prediction.sql
--
-- The prediction store (P2-3): every answer this API issued, kept as it was served.
--
-- Until now a `POST /api/predict/team-selection` answer was assembled from four
-- ml-service calls, returned to the Lab and gone. Nothing held what it claimed, so when
-- the match it was about was finally imported there was nothing to score against the
-- result. This table is that missing half: one row per successful answer, holding the
-- exact payload the caller received, the request it answered, and the rating state it was
-- served from. P2-4 reads it and scores it; nothing else writes it.
--
-- This is not a revival of `match_prediction_aggregates`, which migration 0007 dropped.
-- That table was a *cache*: predicted runs, wickets, extras and a winner for a match that
-- had already been played, written by the per-match backtest flow and read back by an
-- accuracy trend, and every row in it could be recomputed by running the flow again. It
-- went when the five models that filled it went. This table holds the opposite kind of
-- thing: answers about *upcoming* fixtures, issued at a moment, from a rating state that
-- a later retrain replaces. Once `run_id` is no longer the loaded run, nothing in this
-- system can reproduce a single row here -- which is precisely why they are kept.
--
-- Why the payload is stored whole. A scorer written a year from now must never find that
-- the field it needs was not one of the columns somebody thought to add in 2026, and a
-- record that shows "what we claimed" has to be able to show the claim itself and not a
-- summary of it. `jsonb` keeps the JSON *value* exactly -- every field, every number,
-- every null -- and normalises only insignificant whitespace and key order, neither of
-- which any reader of the record can be affected by.
--
-- Why the columns beside it. They are the resolver's join key and the record's sort key,
-- and nothing else: `format_code`, both opposition ids, `gender` and `match_date` are how
-- an imported `match` row is matched to the prediction that was about it; `issued_at` is
-- the order a record is read in; `run_id` and `ratings_through` are the rating state, and
-- are columns because a record is grouped and filtered by run without parsing 22 payloads
-- to do it. `selection_objective` separates a searched eleven from one the caller pinned
-- in Play mode -- `fixed` is a scenario, listed and never scored (roadmap § 5, clause 5).
-- `win_probability_team1` and its source are the headline claim, which is what a Brier is
-- computed over. Every one of them is also inside `payload` or `request`; nothing derived
-- that those two documents do not already say is stored here.

BEGIN;

CREATE TABLE IF NOT EXISTS public.issued_prediction (
    -- Generated by go-app before the insert, because the id is inside `payload`: the row
    -- holds the bytes that left the server, and those bytes name the row.
    id                     uuid        PRIMARY KEY,
    issued_at              timestamptz NOT NULL,

    -- The rating state the answer was computed from, off the answer itself (P1-5) and
    -- never off a status read, which describes whatever is loaded at the moment of the
    -- read rather than what served this prediction.
    run_id                 text        NOT NULL,
    ratings_through        date        NOT NULL,

    -- The fixture, as a resolver joins on it.
    format_code            text        NOT NULL,
    team1_opposition_id    bigint      NOT NULL REFERENCES public.opposition (id),
    team2_opposition_id    bigint      NOT NULL REFERENCES public.opposition (id),
    gender                 text        NOT NULL,
    match_date             date        NOT NULL,

    -- 'win', 'ratings' or 'fixed' -- go-app's selection vocabulary, declared in
    -- contracts/ops-console.contract.json and asserted from both sides (H-24).
    selection_objective    text        NOT NULL,

    -- The headline claim and the model behind it ('display' or 'simulator').
    win_probability_team1  double precision NOT NULL,
    win_probability_source text        NOT NULL,

    request                jsonb       NOT NULL,
    payload                jsonb       NOT NULL
);

COMMENT ON TABLE public.issued_prediction IS
    'One issued prediction, kept as it was served (P2-3): the exact payload, its request, and the run and date it came from';
COMMENT ON COLUMN public.issued_prediction.payload IS
    'The answer the caller received, whole -- including its own `record` block, which names this row';
COMMENT ON COLUMN public.issued_prediction.selection_objective IS
    '"win" or "ratings" for an eleven this service chose, "fixed" for one the caller pinned in Play mode (a scenario)';

-- The record reads newest first.
CREATE INDEX IF NOT EXISTS issued_prediction_issued_at_idx
    ON public.issued_prediction (issued_at DESC);

-- The resolver asks "which predictions were about the matches this import just brought?",
-- which is a scan by match date narrowed by the fixture's own identity.
CREATE INDEX IF NOT EXISTS issued_prediction_fixture_idx
    ON public.issued_prediction (match_date, format_code, team1_opposition_id, team2_opposition_id);

COMMIT;
